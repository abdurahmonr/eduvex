-- 4. FOYDALANUVCHINI O'CHIRISH FUNKSIYASI (RPC)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.delete_user_by_admin(user_id UUID)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
BEGIN
    DELETE FROM public.profiles WHERE id = user_id;
    DELETE FROM public.admins WHERE email IN (SELECT email FROM public.profiles WHERE id = user_id);
    DELETE FROM auth.users WHERE id = user_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.delete_user_by_admin(UUID) TO anon, authenticated, service_role;
