-- 2. JADVALLARNI YARATISH (BARCHA KERAKLI USTUNLAR BILAN)
-- ==============================================================================

-- 2.1 Direktorlar jadvali (directors)
CREATE TABLE IF NOT EXISTS public.directors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    login TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    phone TEXT,
    role TEXT NOT NULL DEFAULT 'director',
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.2 Administratorlar jadvali (admins)
CREATE TABLE IF NOT EXISTS public.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    login TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    phone TEXT,
    role TEXT NOT NULL DEFAULT 'admin',
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.3 Foydalanuvchilar profillari (profiles: Supabase Auth users bilan sinxron)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    login TEXT,
    password TEXT,
    phone TEXT,
    role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('director', 'admin')),
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Mavjud profiles jadvaliga yangi ustunlarni xatosiz qo'shish
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS login TEXT;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS password TEXT;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS phone TEXT;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active';

-- 2.4 O'qituvchilar (teachers)
CREATE TABLE IF NOT EXISTS public.teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    subject TEXT,
    login TEXT UNIQUE,
    password TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.teachers ADD COLUMN IF NOT EXISTS subject TEXT;
ALTER TABLE public.teachers ADD COLUMN IF NOT EXISTS login TEXT;
ALTER TABLE public.teachers ADD COLUMN IF NOT EXISTS password TEXT;
ALTER TABLE public.teachers ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active';

-- 2.5 Kurslar (courses)
CREATE TABLE IF NOT EXISTS public.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    description TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.courses ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE public.courses ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active';

-- 2.6 Guruhlar (groups)
CREATE TABLE IF NOT EXISTS public.groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    course_id BIGINT REFERENCES public.courses(id) ON DELETE RESTRICT,
    teacher_id BIGINT REFERENCES public.teachers(id) ON DELETE RESTRICT,
    days TEXT NOT NULL,
    time TEXT NOT NULL,
    room TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.groups ADD COLUMN IF NOT EXISTS room TEXT;
ALTER TABLE public.groups ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active';

-- 2.7 O'quvchilar (students)
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    parent_phone TEXT,
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.students ADD COLUMN IF NOT EXISTS notes TEXT;
ALTER TABLE public.students ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active';

-- 2.8 Guruhga biriktirish (enrollments)
CREATE TABLE IF NOT EXISTS public.enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    group_id BIGINT REFERENCES public.groups(id) ON DELETE CASCADE,
    start_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_student_group UNIQUE (student_id, group_id)
);
ALTER TABLE public.enrollments ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active';

-- 2.9 Davomat (attendance)
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    group_id BIGINT REFERENCES public.groups(id) ON DELETE CASCADE,
    date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'keldi' CHECK (status IN ('keldi', 'kelmadi', 'sababli')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_student_group_date UNIQUE (student_id, group_id, date)
);

-- 2.10 To'lovlar (payments)
CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    amount NUMERIC NOT NULL DEFAULT 0,
    date TEXT NOT NULL,
    month TEXT NOT NULL,
    payment_method TEXT DEFAULT 'naqd',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.payments ADD COLUMN IF NOT EXISTS payment_method TEXT DEFAULT 'naqd';

-- 2.11 Lidlar (leads) - Landing arizalari
CREATE TABLE IF NOT EXISTS public.leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    course_name TEXT,
    status TEXT DEFAULT 'yangi',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

